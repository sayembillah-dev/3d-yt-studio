#!/usr/bin/env node
// props_catalog.mjs: writes Engine/references/props-catalog.md, a one-line-per-prop index of every reusable set piece
// (props/*, world/*, fx/*), so a build reads ~2k tokens instead of ~1,700 lines of prop code.
//   node Engine/scripts/props_catalog.mjs [--check]     --check: exit 1 if the catalog is stale (prop added, not indexed)
// Per file: its header comment (theme, first video). Per export: name, props it takes (from the destructured
// parameter or its type), and the comment right above it, if any. Run after adding props (SKILL.md Phase 8).
import path from 'node:path';
import fs from 'node:fs';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const STUDIO = process.env.STUDIO || path.join(HERE, '..', 'studio');
const ts = createRequire(path.join(STUDIO, 'package.json'))('typescript');
const ENGINE = path.join(STUDIO, 'src', 'engine');
const OUT = path.join(HERE, '..', 'references', 'props-catalog.md');
const DIRS = ['props', 'world', 'fx'];

const clean = (s) => s.replace(/^\/\*+|\*+\/$/g, '').split('\n').map((l) => l.replace(/^\s*(\*|\/\/)\s?/, '').replace(/-{4,}/g, '').trim()).filter(Boolean).join(' ');
const COMMON = new Set(['pos', 'rot', 'scale', 'seed']);   // nearly every prop takes these: listed once in the header
const short = (s, n = 150) => (s.length > n ? s.slice(0, n - 1).trimEnd() + '…' : s);

function leadingComment(src, node) {
  const rs = ts.getLeadingCommentRanges(src, node.getFullStart()) || [];
  return rs.length ? clean(src.slice(rs[rs.length - 1].pos, rs[rs.length - 1].end)) : '';
}
function paramNames(fn, sf) {
  const p = fn?.parameters?.[0];
  if (!p) return [];
  if (ts.isObjectBindingPattern(p.name)) return p.name.elements.filter((e) => !COMMON.has(e.name.getText(sf))).map((e) => e.name.getText(sf) + (e.initializer ? `=${short(e.initializer.getText(sf), 18)}` : ''));
  const t = p.type;
  if (t && ts.isTypeLiteralNode(t)) return t.members.map((m) => m.name?.getText(sf) + (m.questionToken ? '?' : '')).filter(Boolean);
  return t ? [t.getText(sf)] : [];
}

const files = DIRS.flatMap((d) => {
  const dir = path.join(ENGINE, d);
  return fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.tsx?$/.test(f) && !f.startsWith('.')).map((f) => path.join(dir, f)) : [];
});
let md = `# Props catalog (generated by \`node Engine/scripts/props_catalog.mjs\`; do not edit by hand)\n` +
  `Import with \`import {Name} from '@engine/<dir>/<file>'\`. Every prop is toon-lit and inked; most also take pos, rot,\n` +
  `scale, seed (left out below). Read the source only for the\n` +
  `ones you use. New reusable props go in the matching theme file (or a new \`props/<era-or-theme>.tsx\` with a header\n` +
  `comment), then re-run this script.\n`;
let count = 0;
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  const sf = ts.createSourceFile(f, src, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TSX);
  const first = sf.statements[0];
  const header = first ? leadingComment(src, first) : '';
  const rows = [];
  for (const st of sf.statements) {
    const exported = st.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
    if (!exported) continue;
    const note = st === first ? '' : leadingComment(src, st);
    if (ts.isFunctionDeclaration(st) && st.name) rows.push([st.name.text, paramNames(st, sf), note]);
    else if (ts.isVariableStatement(st)) for (const d of st.declarationList.declarations) {
      if (!ts.isIdentifier(d.name)) continue;
      let init = d.initializer;
      while (init && (ts.isCallExpression(init) || ts.isParenthesizedExpression(init) || ts.isAsExpression(init))) init = ts.isCallExpression(init) ? init.arguments[0] : init.expression;
      const fn = init && (ts.isArrowFunction(init) || ts.isFunctionExpression(init)) ? init : null;
      rows.push([d.name.text, fn ? paramNames(fn, sf) : null, note]);
    }
  }
  if (!rows.length) continue;
  md += `\n## ${path.relative(ENGINE, f).replace(/\.tsx?$/, '')}\n${header ? short(header, 400) + '\n' : ''}`;
  for (const [name, params, note] of rows) {
    count++;
    const sig = params === null ? ' (value)' : `(${short(params.join(', '), 110)})`;
    md += `- **${name}**${sig}${note ? ' — ' + short(note) : ''}\n`;
  }
}
if (process.argv.includes('--check')) {
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  console.log(old === md ? `PROPS_CATALOG: up to date (${count} exports)` : 'PROPS_CATALOG: STALE: run node Engine/scripts/props_catalog.mjs');
  process.exit(old === md ? 0 : 1);
}
fs.writeFileSync(OUT, md);
console.log(`${OUT}\n${count} exports from ${files.length} files, ~${Math.round(md.length / 4)} tokens`);
